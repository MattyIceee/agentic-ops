# Node 6: self_review
# ---------------------------------------------------------------------------

_SELF_REVIEW_SYSTEM = """\
You are a Kubernetes manifest reviewer. Check the generated manifests against
the provided conventions and this checklist:

- All required fields are present (apiVersion, kind, metadata.name, etc.)
- Namespace is set and matches the spec
- Container image reference is not a placeholder ("unknown", "TODO", etc.)
- Port numbers in the Service selector match those in the Deployment
- Labels and selectors are consistent between Deployment and Service
- No raw secret values in env (use secretKeyRef or separate Secret objects)
- Follows the repository conventions

Return ONLY a JSON object: {"passed": true/false, "issues": ["issue 1", ...]}
If there are no issues, return {"passed": true, "issues": []}
"""


def self_review(state: DeployScaffoldState) -> dict[str, Any]:
    """Check generated manifests against conventions; structured output."""
    manifests = state.get("manifests", {})
    if not manifests:
        return {"review_passed": False, "review_issues": ["No manifests were generated."]}

    manifest_block = "\n\n".join(
        f"### {fname}\n```yaml\n{content}\n```" for fname, content in manifests.items()
    )

    llm = get_llm("extract")
    structured_llm = llm.with_structured_output(ReviewResult)

    messages = [
        SystemMessage(content=_SELF_REVIEW_SYSTEM),
        HumanMessage(
            content=(
                f"Service spec: {json.dumps(state.get('spec', {}), indent=2)}\n\n"
                f"Conventions:\n{state.get('conventions', '')}\n\n"
                f"Generated manifests:\n{manifest_block}"
            )
        ),
    ]

    result: ReviewResult = structured_llm.invoke(messages)  # type: ignore[assignment]
    return {"review_passed": result.passed, "review_issues": result.issues}


# ---------------------------------------------------------------------------
# Node 7: commit_and_pr
# ---------------------------------------------------------------------------


def commit_and_pr(state: DeployScaffoldState) -> dict[str, Any]:
    """Write manifests to the repo working tree, commit, push, open a Gitea PR."""
    settings = get_settings()
    repo_path = settings.example_repo_path
    if not repo_path:
        return {"pr_url": "ERROR: example_repo_path not configured; cannot commit."}

    spec = state.get("spec", {})
    service_name = spec.get("name", "service")
    branch = f"ops-agent/deploy-{service_name}"
    manifests = state.get("manifests", {})

    deploy_dir = Path(repo_path) / "apps" / service_name
    deploy_dir.mkdir(parents=True, exist_ok=True)
    for fname, content in manifests.items():
        (deploy_dir / fname).write_text(content, encoding="utf-8")

    try:
        repo = gitlib.Repo(repo_path)
        new_branch = repo.create_head(branch)
        new_branch.checkout()
        repo.git.add(A=True)
        author = gitlib.Actor(settings.git_author_name, settings.git_author_email)
        issue_number = state.get("issue_number")
        commit_msg = f"feat: add {service_name} deployment manifests"
        if issue_number:
            commit_msg += f" #{issue_number}"
        repo.index.commit(
            commit_msg,
            author=author,
            committer=author,
        )
        repo.remotes.origin.push(refspec=f"{branch}:{branch}")
    except Exception as exc:
        return {"pr_url": f"Git error: {exc}"}

    owner: str = state.get("_owner", "")  # type: ignore[typeddict-item]
    repo_name: str = state.get("_repo", "")  # type: ignore[typeddict-item]

    if not owner or not repo_name:
        return {"pr_url": f"Branch '{branch}' pushed. Set _owner/_repo in state to auto-open PR."}

    try:
        client = GiteaClient()
        try:
            pr = client.create_pr(
                owner=owner,
                repo=repo_name,
                title=f"feat: deploy {service_name}",
                body=_build_pr_body(state),
                head=branch,
                base="main",
            )
            pr_url = pr.get("html_url", str(pr))
        finally:
            client.close()
    except Exception as exc:
        pr_url = f"Branch pushed but PR creation failed: {exc}"

    return {"pr_url": pr_url}


# ---------------------------------------------------------------------------
# Routing functions
# ---------------------------------------------------------------------------


def _route_after_conventions(
    state: DeployScaffoldState,
) -> Literal["generate_helmrelease", "generate_kustomize"]:
    """Route to Helm or Kustomize generator based on helm_chart_found."""
    return "generate_helmrelease" if state.get("helm_chart_found") else "generate_kustomize"


def _route_after_review(
    state: DeployScaffoldState,
) -> Literal["generate_helmrelease", "generate_kustomize", "commit_and_pr"]:
    """Retry the generate node if review failed and retries remain; else commit."""
    passed = state.get("review_passed", False)
    retries = state.get("retry_count", 0)

    if not passed and retries < MAX_RETRIES:
        return "generate_helmrelease" if state.get("helm_chart_found") else "generate_kustomize"
    return "commit_and_pr"


# ---------------------------------------------------------------------------
# Graph assembly
# ---------------------------------------------------------------------------


def build_scaffold_graph() -> Any:
    """Build and compile the deployment scaffolder graph.

    Topology:
      parse_request → research_service → assess_helm → load_conventions
      → (helm?) → generate_helmrelease / generate_kustomize
      → self_review → (passed? retries?) → commit_and_pr / retry generate
      → END

    Compiled with checkpointing support if PostgreSQL is available.
    """
    from ops_agent.checkpointing import get_checkpoint_saver

    graph = StateGraph(DeployScaffoldState)

    graph.add_node("parse_request", parse_request)
    graph.add_node("research_service", research_service)
    graph.add_node("assess_helm", assess_helm)
    graph.add_node("load_conventions", load_conventions)
    graph.add_node("generate_helmrelease", generate_helmrelease)
    graph.add_node("generate_kustomize", generate_kustomize)
    graph.add_node("self_review", self_review)
    graph.add_node("commit_and_pr", commit_and_pr)

    graph.set_entry_point("parse_request")
    graph.add_edge("parse_request", "research_service")
    graph.add_edge("research_service", "assess_helm")
    graph.add_edge("assess_helm", "load_conventions")

    graph.add_conditional_edges(
        "load_conventions",
        _route_after_conventions,
        {
            "generate_helmrelease": "generate_helmrelease",
            "generate_kustomize": "generate_kustomize",
        },
    )

    graph.add_edge("generate_helmrelease", "self_review")
    graph.add_edge("generate_kustomize", "self_review")

    graph.add_conditional_edges(
        "self_review",
        _route_after_review,
        {
            "generate_helmrelease": "generate_helmrelease",
            "generate_kustomize": "generate_kustomize",
            "commit_and_pr": "commit_and_pr",
        },
    )

    graph.add_edge("commit_and_pr", END)

    checkpointer = get_checkpoint_saver()
    if checkpointer:
        return graph.compile(checkpointer=checkpointer)
    return graph.compile()


# ---------------------------------------------------------------------------
# Public run helper
# ---------------------------------------------------------------------------


def run(
    prompt: str,
    owner: str = "",
    repo: str = "",
    issue_number: int | None = None,
    id: str | None = None,
    thread_id: str | None = None,
) -> str | None:
    """Run the full scaffold graph for a deployment request.

    If thread_id is provided, the graph will resume from checkpoint if it exists.
    Otherwise, a fresh run is performed.

    Args:
        prompt: Deployment request text
        owner: Optional Gitea repo owner
        repo: Optional Gitea repo name
        issue_number: Optional issue number to link
        id: Optional explicit checkpoint ID (required if using prompt/prompt_file without issue)
        thread_id: Optional explicit thread ID for checkpointing

    Returns the PR URL from the final state, or None if not set.
    """
    compiled = build_scaffold_graph()

    # Determine the checkpoint thread_id
    if thread_id:
        checkpoint_id = thread_id
    elif issue_number:
        checkpoint_id = f"issue_{issue_number}"
    elif id:
        checkpoint_id = id
    else:
        checkpoint_id = "scaffold_deploy_no_id"

    initial_state: dict[str, Any] = {
        "request": prompt,
        "thread_id": checkpoint_id,
        "provided_links": [],
        "spec": {},
        "service_evidence": [],
        "helm_chart_found": False,
        "helm_chart_ref": None,
        "conventions": "",
        "manifests": {},
        "review_passed": False,
        "review_issues": [],
        "retry_count": 0,
        "pr_url": None,
        "_owner": owner,
        "_repo": repo,
        "issue_number": issue_number,
    }

    # Use thread_id for checkpoint resumption if available
    if checkpoint_id and checkpoint_id != "scaffold_deploy_no_id":
        final_state = compiled.invoke(initial_state, config={"configurable": {"thread_id": checkpoint_id}})
    else:
        final_state = compiled.invoke(initial_state)
    return final_state.get("pr_url")
